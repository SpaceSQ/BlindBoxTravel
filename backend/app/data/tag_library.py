def catalog_pairs() -> list[tuple[str, str, str, list[tuple[str, str]]]]:
    """(key, label, declared is checked separately) -> pairs of (中文, English)."""
    built: list[tuple[str, str, str, list[tuple[str, str]]]] = []
    missing: list[str] = []
    seen_en: dict[str, str] = {}
    for key, label, _declared, text in SECTIONS:
        names = _names(text)
        # drop the temporary marker if it leaked
        names = [name for name in names if name != "LGBTQ待补"]
        pairs: list[tuple[str, str]] = []
        for name in names:
            english = EN.get(name)
            if not english:
                missing.append(name)
                continue
            previous = seen_en.get(english.casefold())
            if previous and previous != name:
                raise ValueError(f"英文重复：{english} 同时对应 {previous} 和 {name}")
            seen_en[english.casefold()] = name
            pairs.append((name, english))
        built.append((key, label, str(_declared_of(key)), pairs))
    if missing:
        raise ValueError("缺少英文：" + "、".join(missing))
    return built


def _declared_of(key: str) -> int:
    for item_key, _label, declared, _text in SECTIONS:
        if item_key == key:
            return declared
    raise KeyError(key)


def iter_entries() -> list[tuple[str, str, int, str, str]]:
    """key, label, declared, chinese, english. Repeats a name when it sits in two dimensions."""
    rows: list[tuple[str, str, int, str, str]] = []
    for key, label, declared, text in SECTIONS:
        names = [name for name in _names(text) if name != "LGBTQ待补"]
        if len(names) != declared:
            raise ValueError(f"{key} 声明 {declared} 个，实际 {len(names)}")
        for name in names:
            rows.append((key, label, declared, name, EN[name]))
    return rows
